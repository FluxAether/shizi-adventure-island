export function captionAllowed(hanzi, caption) {
  if (!caption) return true;
  if (BLOCKED_CAPTIONS.has(caption)) return false;
  if (caption.includes(hanzi)) return true;
  return CAPTION_ALIASES[hanzi]?.has(caption) === true;
}

export function illustrationFor(hanzi) {
  const spec = CHARACTER_ILLUSTRATIONS[hanzi] ?? { motif: 'action', variant: 'action', caption: '' };
  const meta = MOTIF_META[spec.motif] ?? MOTIF_META.action;
  const picture = MOTIF_ALT[spec.motif] ?? '图画';
  const caption = captionAllowed(hanzi, spec.caption) ? spec.caption : '';
  const alt = caption ? `${hanzi}字，图画是${caption}` : `${hanzi}字，图画是${picture}`;
  return {
    theme: meta.theme,
    illustration: {
      motif: spec.motif,
      variant: spec.variant,
      caption,
      alt,
      sceneId: meta.sceneId,
    },
  };
}

